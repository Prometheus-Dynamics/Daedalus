//! The struct a module defines and its port functions.

use alloc::format;
use alloc::string::String;
use alloc::vec::Vec;
use core::fmt::Write as _;

use super::emit::{CHIP, Module};
use super::tunable;

fn queue_text(module: &Module) -> Vec<String> {
    module
        .queues
        .iter()
        .enumerate()
        .map(|(index, edge)| {
            format!(
                "    /// {}\n    e{index}: {CHIP}::Queue<{}, {}>,",
                edge.label, edge.ty, edge.capacity
            )
        })
        .collect()
}

fn names(items: &[String]) -> String {
    let quoted: Vec<String> = items.iter().map(|item| format!("{item:?}")).collect();
    quoted.join(", ")
}

/// The whole module.
pub(super) fn graph_struct(module: &Module, tick: &str) -> String {
    let name = &module.name;
    let mut out = String::new();
    out.push_str("// @generated by Daedalus; do not edit.\n\n");
    let labels: Vec<String> = module
        .queues
        .iter()
        .map(|edge| edge.label.clone())
        .collect();
    let _ = writeln!(
        out,
        "/// Nodes in run order (`ChipError::Node::node`).\npub const NODE_IDS: [&str; {}] = [{}];\n/// Queues (`ChipError::QueueFull::edge`).\npub const EDGES: [&str; {}] = [{}];\n",
        module.ids.len(),
        names(&module.ids),
        labels.len(),
        names(&labels),
    );
    out.push_str(&tunable::tables(&module.params));
    let _ = writeln!(
        out,
        "/// The planned graph: one queue per edge, one state per node."
    );
    let _ = writeln!(out, "pub struct {name} {{");
    for line in queue_text(module) {
        let _ = writeln!(out, "{line}");
    }
    for (step, ty) in &module.states {
        let _ = writeln!(out, "    s{step}: Option<{ty}>,");
    }
    for (id, param) in module.params.iter().enumerate() {
        let _ = writeln!(
            out,
            "    /// {}\n    p{id}: {},",
            param.name,
            param.kind.key()
        );
    }
    out.push_str("}\n\n");
    let _ = writeln!(
        out,
        "impl Default for {name} {{\n    fn default() -> Self {{\n        Self::new()\n    }}\n}}\n"
    );
    let _ = writeln!(
        out,
        "#[allow(clippy::all, unused_variables, unused_labels, unused_mut, unused_assignments)]"
    );
    let _ = writeln!(out, "impl {name} {{");
    out.push_str("    pub const fn new() -> Self {\n        Self {\n");
    for index in 0..module.queues.len() {
        let _ = writeln!(out, "            e{index}: {CHIP}::Queue::new(),");
    }
    for (step, _) in &module.states {
        let _ = writeln!(out, "            s{step}: None,");
    }
    for (id, param) in module.params.iter().enumerate() {
        let _ = writeln!(out, "            p{id}: {},", param.value);
    }
    out.push_str("        }\n    }\n");
    for port in &module.inputs {
        let _ = writeln!(
            out,
            "\n    /// Pushes a value to host input `{}`.\n    pub fn push_{}(&mut self, value: {}) -> Result<(), {CHIP}::ChipError> {{",
            port.name, port.ident, port.ty
        );
        for edge in &port.edges {
            let overflow = match module.queues[*edge].overflow {
                daedalus_runner::Overflow::DropOldest => "DropOldest",
                daedalus_runner::Overflow::DropNewest => "DropNewest",
                daedalus_runner::Overflow::Error => "Error",
            };
            let _ = writeln!(
                out,
                "        {CHIP}::push(&mut self.e{edge}, value, {CHIP}::Overflow::{overflow}, {edge})?;"
            );
        }
        out.push_str("        Ok(())\n    }\n");
    }
    for port in &module.outputs {
        let _ = writeln!(
            out,
            "\n    /// Takes the oldest value of host output `{}`.\n    pub fn pop_{}(&mut self) -> Option<{}> {{\n        self.e{}.pop()\n    }}",
            port.name, port.ident, port.ty, port.edges[0]
        );
    }
    let _ = writeln!(
        out,
        "\n    /// Runs every node once, with the time at zero.\n    pub fn tick(&mut self) -> Result<(), {CHIP}::ChipError> {{\n        self.tick_at(0)\n    }}\n\n    /// [`Self::tick`] at the time `clock` reads.\n    pub fn tick_with(&mut self, clock: &impl {CHIP}::Clock) -> Result<(), {CHIP}::ChipError> {{\n        self.tick_at({CHIP}::Clock::now_ns(clock))\n    }}\n"
    );
    out.push_str(tick);
    out.push_str(&tunable::setters(&module.params));
    out.push_str("}\n");
    out.push_str(&tunable::tunable_impl(name, &module.params));
    out
}
